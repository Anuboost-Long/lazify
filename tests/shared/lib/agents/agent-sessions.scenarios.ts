function writeTree(root: string, files: Record<string, { body: string; mtime: number }>) {
	for (const [relative, { body, mtime }] of Object.entries(files)) {
		const file = path.join(root, relative);
		fs.mkdirSync(path.dirname(file), { recursive: true });
		fs.writeFileSync(file, body);
		fs.utimesSync(file, mtime, mtime);
	}
}

export async function exercise(listAgentSessions: ListAgentSessions): Promise<Record<string, unknown>> {
	const home = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "agent-sessions-")));
	const previousHome = process.env.HOME;

	writeTree(path.join(home, ".claude", "projects", "-work-web"), CLAUDE_FILES);
	writeTree(path.join(home, ".codex", "sessions"), CODEX_FILES);
	const empty = fs.mkdtempSync(path.join(os.tmpdir(), "agent-sessions-empty-"));

	try {
		process.env.HOME = home;
		const results: Record<string, unknown> = {
			all: await listAgentSessions("/work/web"),
			limited: await listAgentSessions("/work/web", 3),
			otherProject: await listAgentSessions("/work/api"),
			neverRun: await listAgentSessions("/work/none"),
		};

		process.env.HOME = empty;
		results.noTranscripts = await listAgentSessions("/work/web");

		return results;
	} finally {
		process.env.HOME = previousHome;
		fs.rmSync(home, { recursive: true, force: true });
		fs.rmSync(empty, { recursive: true, force: true });
	}
}
