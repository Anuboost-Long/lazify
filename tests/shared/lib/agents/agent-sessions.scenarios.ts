const snapshot = { type: "file-history-snapshot", files: "s".repeat(CHUNK + 1234) };
const straddling = (() => {
	const prompt = JSON.stringify(user("café ☕ — résumé naïve 日本語 prompt"));
	const intoCup = Buffer.byteLength(prompt.slice(0, prompt.indexOf("☕"))) + 1;
	const padding = CHUNK - intoCup - 1 - JSON.stringify({ type: "summary", pad: "" }).length;
	return `${JSON.stringify({ type: "summary", pad: "p".repeat(padding) })}\n${prompt}`;
})();

